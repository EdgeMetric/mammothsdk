#!/usr/bin/env python3
"""Count the CLI calls a task needs with its recipe and without (#309).

For each executable recipe in ``discovery/recipes.json`` this counts the calls an agent
makes to finish the task two ways:

* **step by step**: one call per prose step of the recipe (what ``mammoth how`` prints), and
  the same count plus one ``schema get`` per distinct command, for an agent that has to read
  each command's input fields before it can call it;
* **with the recipe**: one ``mammoth recipe run``, or two when a write is previewed with
  ``--dry-run`` first.

It is an offline count over the shipped data, so it is deterministic and needs no login. It
measures how many calls a task takes, not whether an agent gets the task right: that needs
the live eval (``tests/live``, ``pytest -m live``) and a dev profile. Both ways begin with
the same discovery call (``mammoth how`` or ``schema find``), which is left out of both.

Usage:
    python scripts/eval_task_calls.py            # print the table
    python scripts/eval_task_calls.py --write    # rewrite docs/task-call-eval.md
    python scripts/eval_task_calls.py --check    # exit 1 when docs/task-call-eval.md is stale
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from mammoth_cli.discovery import runnable_recipes, writes

DOC = Path(__file__).resolve().parents[1] / "docs" / "task-call-eval.md"

_HEADER = """# Calls per common task: recipe versus step by step

Generated by `scripts/eval_task_calls.py` from `mammoth_cli/discovery/recipes.json`. Do not
edit by hand: run `python scripts/eval_task_calls.py --write`.

This counts CLI calls, not accuracy. Step by step is one call per prose step of the recipe
(`mammoth how`); with lookups adds one `schema get` per distinct command. With the recipe is
one `mammoth recipe run`; with a preview adds the `--dry-run` call a careful agent makes before
a write. The discovery call that finds the task is the same on both sides and is not counted.
Whether an agent finishes the task correctly is measured by the live eval (`pytest -m live`).
"""


@dataclass(frozen=True)
class TaskCalls:
    """The call counts for one task.

    Attributes:
        task: The recipe id.
        writes: Whether the task changes something.
        lines: The commands the recipe runs inside its one call.
        manual: Calls step by step, one per prose step.
        manual_lookups: Step-by-step calls plus one ``schema get`` per distinct command.
        recipe: Calls with the recipe.
        recipe_preview: Calls with the recipe, previewed first when the task writes.
    """

    task: str
    writes: bool
    lines: int
    manual: int
    manual_lookups: int
    recipe: int
    recipe_preview: int


def count(recipe: dict[str, Any]) -> TaskCalls:
    """The call counts for one executable recipe.

    Args:
        recipe: An executable recipe from ``recipes.json``.

    Returns:
        The counts, step by step and with the recipe.
    """
    steps = recipe["steps"]
    distinct = {step["command_id"] for step in steps}
    changes = writes(recipe)
    return TaskCalls(
        task=recipe["id"],
        writes=changes,
        lines=len(recipe["run"]),
        manual=len(steps),
        manual_lookups=len(steps) + len(distinct),
        recipe=1,
        recipe_preview=2 if changes else 1,
    )


def tasks() -> list[TaskCalls]:
    """The counts for every executable recipe, in file order.

    Returns:
        One record per recipe.
    """
    return [count(recipe) for recipe in runnable_recipes()]


def render(rows: list[TaskCalls]) -> str:
    """The comparison as a markdown document.

    Args:
        rows: The per-task counts from :func:`tasks`.

    Returns:
        The document text, ending in a newline.
    """
    lines = [
        _HEADER,
        "| Task | Writes | Lines in one run | Step by step | With lookups | With recipe | "
        "With preview |",
        "|------|:------:|-----------------:|-------------:|-------------:|------------:|"
        "-------------:|",
    ]
    for row in rows:
        lines.append(
            f"| `{row.task}` | {'yes' if row.writes else 'no'} | {row.lines} | {row.manual} | "
            f"{row.manual_lookups} | {row.recipe} | {row.recipe_preview} |"
        )
    manual = sum(row.manual for row in rows)
    lookups = sum(row.manual_lookups for row in rows)
    recipe = sum(row.recipe for row in rows)
    preview = sum(row.recipe_preview for row in rows)
    lines.append(
        f"| **{len(rows)} tasks** | | {sum(row.lines for row in rows)} | **{manual}** | "
        f"**{lookups}** | **{recipe}** | **{preview}** |"
    )
    fewer = sum(1 for row in rows if row.recipe_preview < row.manual)
    same = sum(1 for row in rows if row.recipe_preview == row.manual)
    lines += [
        "",
        f"With the recipe and a preview the {len(rows)} tasks take {preview} calls. Step by "
        f"step they take {manual} ({lookups} with lookups). {fewer} tasks need fewer calls "
        f"and {same} the same.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Print the table, rewrite the doc, or check that the doc is current.

    Args:
        argv: The command-line arguments (default: ``sys.argv``).

    Returns:
        The process exit status.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else "")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="rewrite docs/task-call-eval.md")
    group.add_argument("--check", action="store_true", help="fail when the doc is stale")
    args = parser.parse_args(argv)
    text = render(tasks())
    if args.write:
        DOC.write_text(text, encoding="utf-8")
        return 0
    if args.check:
        if not DOC.is_file() or DOC.read_text(encoding="utf-8") != text:
            print("docs/task-call-eval.md is stale: run scripts/eval_task_calls.py --write")
            return 1
        return 0
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
